/** D107: the injected Shell Integration line must never be visible or left in history. */
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { SI_DONE, createEchoGate, shellIntegrationScript } from '../src/shared/shell-integration'
const s = shellIntegrationScript()
assert.ok(s.startsWith(' '), 'leading space (ignorespace)')
assert.ok(!s.includes('\x1b'), 'echoed source never contains the real ESC of the marker')
assert.match(s, /builtin history -d/)
assert.ok(s.endsWith("printf '\\033]6973;aiss-si\\007'"))
const g = createEchoGate(5000)
assert.equal(g.feed('x', 0), 'x')
g.start(0)
assert.equal(g.feed(s.slice(0, 80), 10), '')
assert.equal(g.feed(s.slice(80) + '\r\n', 20), '')
assert.equal(g.feed(`\x1b]133;D;0\x07${SI_DONE}`, 30), '\r\x1b[2K')
assert.equal(g.active(), false)
assert.equal(g.feed('[root@test_java01 ~]# ', 40), '[root@test_java01 ~]# ')
g.start(0)
assert.equal(g.feed('echo...' + SI_DONE.slice(0, 4), 1), '')
assert.equal(g.feed(SI_DONE.slice(4) + 'P# ', 2), '\r\x1b[2KP# ')
g.start(0)
assert.equal(g.feed('fish: Unknown command\r\n> ', 100), '')
assert.equal(g.flush(), '> ')
g.start(0)
assert.equal(g.feed('err\r\n$ ', 6000), '$ ')
const tp = readFileSync('src/renderer/src/components/TerminalPane.tsx', 'utf8')
assert.match(tp, /dispatchEvent\(new CustomEvent\(SI_GATE_EVENT[\s\S]{0,80}ssh\.write\(sessionId, `\$\{shellIntegrationScript\(\)\}\\r`\)/)
assert.match(tp, /if \(gate\.active\(\)\) \{/)
assert.match(tp, /isNewTyped\(lastTypedNum, typed\.num\) && !skipFirstE/)
assert.match(tp, /already: wasInjected\(sessionId\)/)
console.log('test-si-hidden ok')
