const catalogs: Record<LocaleId, Record<MessageKey, string>> = {
  'zh-CN': zhCN,
  en
}

export function translate(
  locale: LocaleId,
  key: MessageKey,
  vars?: Record<string, string | number>
): string {
  const template = catalogs[locale][key] ?? catalogs['zh-CN'][key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] != null ? String(vars[name]) : `{${name}}`
  )
}

type I18nValue = {
  locale: LocaleId
  setLocale: (locale: LocaleId) => void
  t: (key: MessageKey, vars?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nValue | null>(null)

let activeLocale: LocaleId = 'zh-CN'

/** Translate with the current UI locale (for helpers / non-hook call sites; components re-render on locale change). */
export function tg(key: MessageKey, vars?: Record<string, string | number>): string {
  return translate(activeLocale, key, vars)
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<LocaleId>('zh-CN')
  activeLocale = locale

  useEffect(() => {
    const api = window.aiss?.workspace?.locale
    if (!api) return
    let cancelled = false
    void api
      .get()
      .then((value) => {
        if (!cancelled) setLocaleState(normalizeLocale(value))
      })
      .catch(() => {
        /* keep default */
      })
    return () => {
      cancelled = true
    }
  }, [])

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const setLocale = useCallback((next: LocaleId) => {
    const value = normalizeLocale(next)
    setLocaleState(value)
    void window.aiss?.workspace?.locale.set(value).catch(() => {
      /* preference stays in memory for this window */
    })
  }, [])

  const t = useCallback(
    (key: MessageKey, vars?: Record<string, string | number>) => translate(locale, key, vars),
    [locale]
  )

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext)
  if (ctx) return ctx
  return {
    locale: 'zh-CN',
    setLocale: () => {
      /* provider missing */
    },
    t: (key, vars) => translate('zh-CN', key, vars)
  }
}
