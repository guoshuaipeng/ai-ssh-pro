/** W1: turn AI fix commands into a reviewable playbook draft. Never executes. */
import { assessCommandRisk } from './command-risk'
import type { ProtectionLevel } from './protection'
import { extractVarNames, isBuiltinVar, isValidVarName } from './template-vars'
import { newStepId, type Playbook, type PlaybookOrigin, type PlaybookStep, type PlaybookVar } from './playbook'

export type { PlaybookOrigin }

export type FixCommand = { command: string; note?: string }

const ANGLE = /<([A-Za-z_][A-Za-z0-9_]*)>/g
const YOUR = /\bYOUR_([A-Za-z_][A-Za-z0-9_]*)\b/g
export const MAX_DRAFT_STEPS = 10
export const DRAFT_STALE_MS = 7 * 24 * 60 * 60 * 1000

const RULE_SHORT: Record<string, { zh: string; en: string }> = {
  cpu: { zh: 'CPU 过高', en: 'high CPU' },
  mem: { zh: '内存过高', en: 'high memory' },
  disk: { zh: '磁盘不足', en: 'low disk' },
  offline: { zh: '离线', en: 'offline' }
}

export function ruleShortName(ruleId: string | undefined, locale: string): string {
  const row = ruleId ? RULE_SHORT[ruleId] : undefined
  if (row) return locale === 'en' ? row.en : row.zh
  return ruleId || ''
}

export function rewritePlaceholders(command: string): { command: string; vars: string[]; check: boolean } {
  const vars: string[] = []
  const take = (name: string) => {
    if (!vars.includes(name)) vars.push(name)
    return `{{${name}}}`
  }
  const next = String(command ?? '').replace(ANGLE, (_w, name: string) => take(name)).replace(YOUR, (_w, name: string) => take(name))
  const check = /<[^>\n]*>/.test(next)
  return { command: next, vars, check }
}

export function playbookFromFixes(
  fixes: FixCommand[],
  origin: PlaybookOrigin,
  level: ProtectionLevel,
  opts?: { profileId?: string; locale?: string; now?: number; ruleLabel?: string }
): { playbook: Playbook; truncated: number; introduced: string[] } {
  const now = opts?.now ?? Date.now()
  const locale = opts?.locale === 'en' ? 'en' : 'zh'
  const rule = opts?.ruleLabel || ruleShortName(origin.ruleId, locale)
  const host = origin.hostTitle
  const seen = new Set<string>()
  const steps: PlaybookStep[] = []
  const introduced: string[] = []
  let dropped = 0
  for (const fix of fixes) {
    const raw = String(fix.command ?? '').trim()
    if (!raw) continue
    const rewritten = rewritePlaceholders(raw)
    if (seen.has(rewritten.command)) continue
    seen.add(rewritten.command)
    if (steps.length >= MAX_DRAFT_STEPS) {
      dropped += 1
      continue
    }
    for (const name of rewritten.vars) if (!introduced.includes(name)) introduced.push(name)
    const danger = Boolean(assessCommandRisk(rewritten.command))
    const locked = danger || level === 'production'
    const note = (fix.note ?? '').trim()
    steps.push({
      id: newStepId(now + steps.length),
      type: 'command',
      command: rewritten.command,
      title: (note || rewritten.command).slice(0, 60),
      confirm: true,
      stopOnError: true,
      timeoutSec: 60,
      aiGenerated: true,
      lockedConfirm: locked || undefined,
      checkPlaceholder: rewritten.check || undefined
    })
  }
  const vars: PlaybookVar[] = introduced.map((name) => ({
    name,
    required: true,
    sensitive: false,
    quote: true
  }))
  const name = locale === 'en' ? `Fix: ${host} ${rule}`.trim() : `修复：${host} ${rule}`.trim()
  const description = locale === 'en' ? 'Generated by AI from an alert; edit as needed' : '由 AI 根据告警生成，可修改'
  const playbook: Playbook = {
    id: `pb-${now}`,
    name,
    description,
    steps,
    updatedAt: now,
    draft: true,
    origin,
    targetHint: opts?.profileId ? [opts.profileId] : [],
    vars
  }
  const inputCount = fixes.filter((f) => String(f.command ?? '').trim()).length
  const truncated = inputCount > steps.length + (seen.size > steps.length ? 0 : 0) ? Math.max(dropped, inputCount - steps.length) : dropped
  return { playbook, truncated: Math.max(dropped, inputCount > MAX_DRAFT_STEPS ? inputCount - steps.length : dropped), introduced }
}

export function findAlertDraft(list: Playbook[], alertId: string): Playbook | undefined {
  return list.find((p) => p.draft && p.origin?.alertId === alertId)
}

export function isStaleDraft(playbook: Playbook, now = Date.now()): boolean {
  return Boolean(playbook.draft) && now - (playbook.updatedAt || 0) >= DRAFT_STALE_MS
}

export function sortPlaybooks(list: Playbook[]): Playbook[] {
  return [...list].sort((a, b) => Number(Boolean(b.draft)) - Number(Boolean(a.draft)) || (b.updatedAt || 0) - (a.updatedAt || 0))
}

export function promoteDraft(playbook: Playbook): Playbook {
  if (!playbook.draft) return playbook
  const { draft: _draft, ...rest } = playbook
  return rest
}

export function discoverVars(playbook: Playbook, snippetBodies: string[] = []): PlaybookVar[] {
  const bodies = [
    ...playbook.steps.map((s) => s.command || ''),
    ...snippetBodies
  ]
  const found = extractVarNames(bodies.join('\n'), 64).filter((n) => !isBuiltinVar(n) && isValidVarName(n))
  const prev = playbook.vars ?? []
  const next: PlaybookVar[] = []
  for (const name of found) {
    const existing = prev.find((v) => v.name === name)
    next.push(existing ?? { name, required: true, sensitive: false, quote: true })
  }
  for (const v of prev) {
    if (!next.some((n) => n.name === v.name)) next.push({ ...v, unused: true })
  }
  return next
}

export function initialHostIds(opts: { targetHint?: string[]; upstream?: string[] }): string[] {
  if (opts.upstream && opts.upstream.length) return [...opts.upstream]
  if (opts.targetHint && opts.targetHint.length) return [...opts.targetHint]
  return []
}
